import type { Column, GenerateRequest, Query } from "./request.ts";
import { type EnumTypes, resolveType } from "./types.ts";

export type GeneratedFile = { path: string; contents: string };

/** Every problem found in one pass, so a single run lists all of them. */
export class GenerateError extends Error {
  readonly problems: readonly string[];

  constructor(problems: readonly string[]) {
    super(problems.join("\n"));
    this.name = "GenerateError";
    this.problems = problems;
  }
}

export const GENERATED_MARKER = "// Code generated by sqlc-ts";

const RESERVED_FILES = new Set(["runtime.ts", "enums.ts"]);
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const SYSTEM_SCHEMAS = new Set(["pg_catalog", "information_schema", "pg_temp"]);

type Field = { key: string; column: string; ts: string; nullable: boolean };

/** What a generated file has to import. */
type Used = { enums: Set<string>; runtime: Set<string> };

type Directives = {
  nullable: Set<string>;
  notNull: Set<string>;
  docs: string[];
};

/**
 * Turns sqlc's analysis into one TS file per query file, plus `enums.ts` when the schema
 * has enums. The runtime file is copied separately (see cli.ts).
 */
export function generate(request: GenerateRequest): GeneratedFile[] {
  const problems: string[] = [];
  const enums = collectEnums(request);
  const byFile = new Map<string, Query[]>();
  for (const query of request.queries) {
    const list = byFile.get(query.filename) ?? [];
    list.push(query);
    byFile.set(query.filename, list);
  }

  const files: GeneratedFile[] = [];
  for (const [filename, queries] of [...byFile].sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const path = `${filename.replace(/\.sql$/, "")}.ts`;
    if (RESERVED_FILES.has(path)) {
      problems.push(`${filename}: rename the file, ${path} is generated`);
      continue;
    }
    const used: Used = { enums: new Set(), runtime: new Set(["Executor"]) };
    const blocks = queries.map((query) =>
      renderQuery(query, enums.types, used, (problem) =>
        problems.push(`${filename} ${query.name}: ${problem}`),
      ),
    );
    files.push({
      path,
      contents: renderFile(filename, request.sqlc_version, blocks, used),
    });
  }
  if (enums.source) {
    files.push({
      path: "enums.ts",
      contents: `${header("the schema", request.sqlc_version)}\n${enums.source}`,
    });
  }
  if (problems.length > 0) throw new GenerateError(problems);
  return files;
}

function collectEnums(request: GenerateRequest): {
  types: EnumTypes;
  source: string;
} {
  const types = new Map<string, string>();
  const decls: string[] = [];
  for (const schema of request.catalog.schemas) {
    if (SYSTEM_SCHEMAS.has(schema.name)) continue;
    for (const item of schema.enums ?? []) {
      const tsName = pascalCase(item.name);
      types.set(item.name.toLowerCase(), tsName);
      types.set(`${schema.name}.${item.name}`.toLowerCase(), tsName);
      const union = item.vals.map((val) => JSON.stringify(val)).join(" | ");
      decls.push(`export type ${tsName} = ${union || "never"};\n`);
    }
  }
  return { types, source: decls.join("\n") };
}

function renderQuery(
  query: Query,
  enums: EnumTypes,
  used: Used,
  report: (problem: string) => void,
): string {
  const directives = parseDirectives(query.comments, report);
  const fn = camelCase(query.name);
  const pascal = pascalCase(query.name);
  if (!IDENTIFIER.test(fn)) {
    report(`query name does not make a valid identifier`);
    return "";
  }

  const resolve = (column: Column, role: "output" | "param") => {
    const resolved = resolveType(column, role, enums);
    if ("error" in resolved) {
      report(`${column.name || "(unnamed)"}: ${resolved.error}`);
      return "unknown";
    }
    for (const name of enums.values()) {
      if (new RegExp(`\\b${name}\\b`).test(resolved.ts)) used.enums.add(name);
    }
    if (resolved.ts.includes("JsonValue")) used.runtime.add("JsonValue");
    return resolved.ts;
  };

  const columns = toFields(query.columns, "column", report, (column) => ({
    ts: resolve(column, "output"),
    nullable: directives.nullable.has(column.name)
      ? true
      : directives.notNull.has(column.name)
        ? false
        : !column.not_null,
  }));
  for (const name of [...directives.nullable, ...directives.notNull]) {
    if (!query.columns.some((column) => column.name === name)) {
      report(
        `@nullable/@notnull names "${name}", which is not a result column`,
      );
    }
  }

  const params = toFields(
    [...query.params]
      .sort((a, b) => a.number - b.number)
      .map((param) => param.column),
    "parameter",
    report,
    (column) => {
      if (column.is_sqlc_slice) {
        report(
          `sqlc.slice() is not supported on Postgres; use = ANY(@name::type[])`,
        );
      }
      return { ts: resolve(column, "param"), nullable: !column.not_null };
    },
  );

  const sqlConst = `${fn}Sql`;
  const out: string[] = [];
  out.push(`const ${sqlConst} = \`${escapeTemplate(query.text)}\`;\n`);
  if (params.length > 0) {
    out.push(`export type ${pascal}Args = ${objectType(params)};\n`);
  }
  if (columns.length > 0) {
    out.push(`export type ${pascal}Row = ${objectType(columns)};\n`);
    used.runtime.add("Row");
  }

  const argsParam = params.length > 0 ? `, args: ${pascal}Args` : "";
  const values = `[${params.map((p) => `args.${p.key}`).join(", ")}]`;
  const toRow =
    columns.length > 0
      ? `(row: Row): ${pascal}Row => (${rowMapper(columns)})`
      : "";
  const docs = directives.docs.length > 0 ? jsdoc(directives.docs) : "";

  switch (query.cmd) {
    case ":one":
      if (columns.length === 0) {
        report(`:one needs result columns; use :exec or :execrows`);
        break;
      }
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<${pascal}Row | null> {\n` +
          `  const { rows } = await db(${sqlConst}, ${values});\n` +
          `  const toRow = ${toRow};\n` +
          `  return rows.length > 0 ? toRow(rows[0]) : null;\n` +
          `}\n`,
      );
      break;
    case ":many":
      if (columns.length === 0) {
        report(`:many needs result columns; use :exec or :execrows`);
        break;
      }
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<${pascal}Row[]> {\n` +
          `  const { rows } = await db(${sqlConst}, ${values});\n` +
          `  return rows.map(${toRow});\n` +
          `}\n`,
      );
      break;
    case ":exec":
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<void> {\n` +
          `  await db(${sqlConst}, ${values});\n` +
          `}\n`,
      );
      break;
    case ":execrows":
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<number> {\n` +
          `  const { rowCount } = await db(${sqlConst}, ${values});\n` +
          `  return rowCount;\n` +
          `}\n`,
      );
      break;
    default:
      report(
        `${query.cmd} is not supported; use :one, :many, :exec or :execrows`,
      );
  }
  return out.join("\n");
}

function toFields(
  columns: readonly Column[],
  kind: "column" | "parameter",
  report: (problem: string) => void,
  describe: (column: Column) => { ts: string; nullable: boolean },
): Field[] {
  const seen = new Set<string>();
  return columns.map((column) => {
    const key = camelCase(column.name);
    if (!IDENTIFIER.test(key)) {
      report(
        `${kind} "${column.name}" does not make a valid identifier; ${
          kind === "column" ? "alias it with AS" : "name it with @name"
        }`,
      );
    } else if (seen.has(key)) {
      report(
        `two ${kind}s map to "${key}"; ${
          kind === "column" ? "alias one with AS" : "name them with @name"
        }`,
      );
    }
    seen.add(key);
    return { key, column: column.name, ...describe(column) };
  });
}

/**
 * `-- @nullable col ...` and `-- @notnull col ...` above a query override sqlc's
 * nullability for result columns. It needs them where it guesses wrong: a cast always
 * reads as NOT NULL, and so does an aggregate such as max() over an outer join.
 */
function parseDirectives(
  comments: readonly string[],
  report: (problem: string) => void,
): Directives {
  const directives: Directives = {
    nullable: new Set(),
    notNull: new Set(),
    docs: [],
  };
  for (const raw of comments) {
    const line = raw.trim();
    const match = /^@(\w+)\s*(.*)$/.exec(line);
    if (!match) {
      directives.docs.push(line);
      continue;
    }
    const [, name, rest] = match;
    const target =
      name === "nullable"
        ? directives.nullable
        : name === "notnull"
          ? directives.notNull
          : null;
    if (!target) {
      report(`unknown directive @${name}`);
      continue;
    }
    for (const column of rest.split(/[\s,]+/).filter(Boolean)) {
      target.add(column);
    }
  }
  return directives;
}

function renderFile(
  filename: string,
  sqlcVersion: string,
  blocks: readonly string[],
  used: Used,
): string {
  const importLine = (names: ReadonlySet<string>, from: string) =>
    names.size > 0
      ? `import type { ${[...names].sort().join(", ")} } from "${from}";\n`
      : "";
  const imports =
    importLine(used.enums, "./enums") + importLine(used.runtime, "./runtime");
  return `${header(filename, sqlcVersion)}\n${imports}\n${blocks.join("\n")}`;
}

export function header(source: string, sqlcVersion: string): string {
  return `${GENERATED_MARKER} from ${source} (sqlc ${sqlcVersion}). DO NOT EDIT.\n`;
}

function objectType(fields: readonly Field[]): string {
  const lines = fields.map(
    (field) => `  ${field.key}: ${field.ts}${field.nullable ? " | null" : ""};`,
  );
  return `{\n${lines.join("\n")}\n}`;
}

function rowMapper(fields: readonly Field[]): string {
  const lines = fields.map((field) => {
    const access = IDENTIFIER.test(field.column)
      ? `row.${field.column}`
      : `row[${JSON.stringify(field.column)}]`;
    const ts = field.nullable ? `${field.ts} | null` : field.ts;
    return `    ${field.key}: ${access} as ${ts},`;
  });
  return `{\n${lines.join("\n")}\n  }`;
}

function jsdoc(lines: readonly string[]): string {
  const body = lines.map((line) => ` * ${line.replaceAll("*/", "*\\/")}`);
  return `/**\n${body.join("\n")}\n */\n`;
}

function escapeTemplate(text: string): string {
  return text
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");
}

export function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

export function pascalCase(name: string): string {
  return name
    .split("_")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}
