import { readdirSync, readFileSync } from "node:fs";
import type { Bind, Dialect, EnumTypes } from "./dialects/dialect.ts";
import { pickDialect, supportedEngines } from "./dialects/index.ts";
import { applyEmbeds, type Embed } from "./embed.ts";
import type { Catalog, Column, GenerateRequest, Query } from "./request.ts";

export type GeneratedFile = { path: string; contents: string };

/** Every problem found in one pass, so a single run lists all of them. */
export class GenerateError extends Error {
  readonly problems: readonly string[];

  constructor(problems: readonly string[]) {
    super(problems.join("\n"));
    this.name = "GenerateError";
    this.problems = problems;
  }
}

export const GENERATED_MARKER = "// Code generated by sqlc-ts";
/** Subdirectory of the output that holds one file per driver adapter. */
export const ADAPTERS_DIR = "adapters";

const RESERVED_FILES = new Set(["runtime.ts", "enums.ts"]);
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
// Names that cannot be declared in a module (strict mode): keywords, future reserved
// words, and the strict-mode-only bindings. They are fine as property names, so only the
// generated function name needs this check.
const RESERVED_WORDS = new Set([
  "arguments",
  "await",
  "break",
  "case",
  "catch",
  "class",
  "const",
  "continue",
  "debugger",
  "default",
  "delete",
  "do",
  "else",
  "enum",
  "eval",
  "export",
  "extends",
  "false",
  "finally",
  "for",
  "function",
  "if",
  "implements",
  "import",
  "in",
  "instanceof",
  "interface",
  "let",
  "new",
  "null",
  "package",
  "private",
  "protected",
  "public",
  "return",
  "static",
  "super",
  "switch",
  "this",
  "throw",
  "true",
  "try",
  "typeof",
  "var",
  "void",
  "while",
  "with",
  "yield",
]);

type Field = {
  key: string;
  column: string;
  ts: string;
  nullable: boolean;
  /** Set for a `sqlc.embed()` column: the table's columns, read from their aliases. */
  embed?: readonly Field[];
};

/**
 * What a generated file has to import (types from enums and runtime, values from runtime)
 * and declare: one type per embedded table, by name.
 */
type Used = {
  enums: Set<string>;
  runtime: Set<string>;
  helpers: Set<string>;
  embeds: Map<string, string>;
};

/** Names a file already uses, which an embedded table's type must not shadow. */
const RUNTIME_TYPES = new Set(["Executor", "Row", "JsonValue"]);

type Directives = {
  nullable: Set<string>;
  notNull: Set<string>;
  docs: string[];
};

/**
 * Turns sqlc's analysis into one TS file per query file, `enums.ts` when the schema has
 * enums, and the dialect's runtime file plus its driver adapters under `adapters/`.
 */
export function generate(request: GenerateRequest): GeneratedFile[] {
  const dialect = pickDialect(request.settings.engine);
  if (!dialect) {
    throw new GenerateError([
      `engine "${request.settings.engine}" is not supported; sqlc-ts knows ${supportedEngines().join(", ")}`,
    ]);
  }
  const problems: string[] = [];
  const enums = collectEnums(request, dialect);
  const byFile = new Map<string, Query[]>();
  for (const query of request.queries) {
    const list = byFile.get(query.filename) ?? [];
    list.push(query);
    byFile.set(query.filename, list);
  }

  const files: GeneratedFile[] = [];
  for (const [filename, queries] of [...byFile].sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const path = `${filename.replace(/\.sql$/, "")}.ts`;
    if (RESERVED_FILES.has(path)) {
      problems.push(`${filename}: rename the file, ${path} is generated`);
      continue;
    }
    const used: Used = {
      enums: new Set(),
      runtime: new Set(["Executor"]),
      helpers: new Set(),
      embeds: new Map(),
    };
    const blocks = queries.map((query) =>
      renderQuery(
        query,
        request.catalog,
        dialect,
        enums.types,
        used,
        (problem) => problems.push(`${filename} ${query.name}: ${problem}`),
      ),
    );
    files.push({
      path,
      contents: renderFile(filename, request.sqlc_version, blocks, used),
    });
  }
  if (enums.source) {
    files.push({
      path: "enums.ts",
      contents: `${header("the schema", request.sqlc_version)}\n${enums.source}`,
    });
  }
  files.push({
    path: "runtime.ts",
    contents: `${header("sqlc-ts", request.sqlc_version)}\n${readFileSync(dialect.runtime, "utf8")}`,
  });
  for (const name of readdirSync(dialect.adapters).sort()) {
    files.push({
      path: `${ADAPTERS_DIR}/${name}`,
      contents: `${header("sqlc-ts", request.sqlc_version)}\n${readFileSync(new URL(name, dialect.adapters), "utf8")}`,
    });
  }
  if (problems.length > 0) throw new GenerateError(problems);
  return files;
}

function collectEnums(
  request: GenerateRequest,
  dialect: Dialect,
): {
  types: EnumTypes;
  source: string;
} {
  const types = new Map<string, string>();
  const decls: string[] = [];
  for (const schema of request.catalog.schemas) {
    if (dialect.systemSchemas.has(schema.name)) continue;
    for (const item of schema.enums ?? []) {
      const tsName = pascalCase(item.name);
      types.set(item.name.toLowerCase(), tsName);
      types.set(`${schema.name}.${item.name}`.toLowerCase(), tsName);
      const union = item.vals.map((val) => JSON.stringify(val)).join(" | ");
      decls.push(`export type ${tsName} = ${union || "never"};\n`);
    }
  }
  return { types, source: decls.join("\n") };
}

function renderQuery(
  query: Query,
  catalog: Catalog,
  dialect: Dialect,
  enums: EnumTypes,
  used: Used,
  report: (problem: string) => void,
): string {
  const directives = parseDirectives(query.comments, report);
  const fn = camelCase(query.name);
  const pascal = pascalCase(query.name);
  if (!IDENTIFIER.test(fn)) {
    report(`query name does not make a valid identifier`);
    return "";
  }
  if (RESERVED_WORDS.has(fn)) {
    report(`"${fn}" is a reserved word in JS; rename the query`);
    return "";
  }

  const resolve = (column: Column, role: "output" | "param") => {
    const resolved = dialect.resolveType(column, role, enums);
    if ("error" in resolved) {
      report(`${column.name || "(unnamed)"}: ${resolved.error}`);
      return "unknown";
    }
    for (const name of enums.values()) {
      if (new RegExp(`\\b${name}\\b`).test(resolved.ts)) used.enums.add(name);
    }
    if (resolved.ts.includes("JsonValue")) used.runtime.add("JsonValue");
    return resolved.ts;
  };

  const embedded = applyEmbeds(query, catalog, dialect, report);
  const nullability = (column: Column) =>
    directives.nullable.has(column.name)
      ? true
      : directives.notNull.has(column.name)
        ? false
        : !column.not_null;
  const columns = toFields(
    query.columns,
    "column",
    dialect,
    report,
    (column, index) => {
      const embed = embedded.embeds.get(index);
      // An embed that applyEmbeds already reported has no type to resolve.
      if (!embed && column.embed_table)
        return { ts: "unknown", nullable: true };
      if (!embed)
        return { ts: resolve(column, "output"), nullable: nullability(column) };
      return {
        ts: embedType(embed, enums, used, dialect, resolve, report),
        // sqlc marks every embed nullable; the join decides, so only @nullable makes it so.
        nullable: directives.nullable.has(column.name),
        embed: embedFields(embed, dialect, resolve, report),
      };
    },
  );
  for (const name of [...directives.nullable, ...directives.notNull]) {
    if (!query.columns.some((column) => column.name === name)) {
      report(
        `@nullable/@notnull names "${name}", which is not a result column`,
      );
    }
  }

  const prepared = dialect.prepareQuery(
    { ...query, text: embedded.text },
    report,
  );
  const params = toFields(
    prepared.params,
    "parameter",
    dialect,
    report,
    (column) => {
      const ts = resolve(column, "param");
      return {
        ts: column.is_sqlc_slice ? arrayOf(ts) : ts,
        nullable: !column.not_null,
      };
    },
  );

  const sqlConst = `${fn}Sql`;
  const out: string[] = [];
  out.push(`const ${sqlConst} = \`${escapeTemplate(prepared.text)}\`;\n`);
  if (params.length > 0) {
    out.push(`export type ${pascal}Args = ${objectType(params)};\n`);
  }
  if (columns.length > 0) {
    out.push(`export type ${pascal}Row = ${objectType(columns)};\n`);
    used.runtime.add("Row");
  }

  const argsParam = params.length > 0 ? `, args: ${pascal}Args` : "";
  const { prelude, call } = invocation(sqlConst, params, prepared.binds, used);
  const toRow =
    columns.length > 0
      ? `(row: Row): ${pascal}Row => (${rowMapper(columns)})`
      : "";
  const docs = directives.docs.length > 0 ? jsdoc(directives.docs) : "";

  switch (query.cmd) {
    case ":one":
      if (columns.length === 0) {
        report(`:one needs result columns; use :exec or :execrows`);
        break;
      }
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<${pascal}Row | null> {\n` +
          prelude +
          `  const { rows } = await db(${call});\n` +
          `  const toRow = ${toRow};\n` +
          `  const first = rows.at(0);\n` +
          `  return first ? toRow(first) : null;\n` +
          `}\n`,
      );
      break;
    case ":many":
      if (columns.length === 0) {
        report(`:many needs result columns; use :exec or :execrows`);
        break;
      }
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<${pascal}Row[]> {\n` +
          prelude +
          `  const { rows } = await db(${call});\n` +
          `  return rows.map(${toRow});\n` +
          `}\n`,
      );
      break;
    case ":exec":
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<void> {\n` +
          prelude +
          `  await db(${call});\n` +
          `}\n`,
      );
      break;
    case ":execrows":
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<number> {\n` +
          prelude +
          `  const { rowCount } = await db(${call});\n` +
          `  return rowCount;\n` +
          `}\n`,
      );
      break;
    case ":execlastid":
      if (!dialect.hasInsertId) {
        report(
          `:execlastid is not supported on ${dialect.engine}; use RETURNING with :one`,
        );
        break;
      }
      out.push(
        `${docs}export async function ${fn}(db: Executor${argsParam}): Promise<number> {\n` +
          prelude +
          `  const { insertId } = await db(${call});\n` +
          `  return insertId;\n` +
          `}\n`,
      );
      break;
    default:
      report(
        `${query.cmd} is not supported; use :one, :many, :exec, :execrows or :execlastid`,
      );
  }
  return out.join("\n");
}

/**
 * The statement and parameter list passed to the executor. Slices need expanding at
 * runtime, so queries with any go through the runtime's expandSlices first, with the
 * scalars grouped by the slice marker they come before.
 */
function invocation(
  sqlConst: string,
  params: readonly Field[],
  binds: readonly Bind[],
  used: Used,
): { prelude: string; call: string } {
  // Every dialect builds its binds from the parameters it returns (a marker with no
  // parameter is reported and binds nothing), so each name is here.
  const keys = new Map(params.map((param) => [param.column, param.key]));
  const list = (group: readonly Bind[]) =>
    `[${group.map((bind) => `args.${keys.get(bind.name)}`).join(", ")}]`;
  if (!binds.some((bind) => bind.slice)) {
    return { prelude: "", call: `${sqlConst}, ${list(binds)}` };
  }
  used.helpers.add("expandSlices");
  const groups: Bind[][] = [[]];
  const slices: Bind[] = [];
  for (const bind of binds) {
    if (bind.slice) {
      slices.push(bind);
      groups.push([]);
    } else {
      groups[groups.length - 1]?.push(bind);
    }
  }
  return {
    prelude: `  const [query, values] = expandSlices(${sqlConst}, [${groups.map(list).join(", ")}], ${list(slices)});\n`,
    call: "query, values",
  };
}

function arrayOf(ts: string): string {
  return ts.includes(" ") ? `(${ts})[]` : `${ts}[]`;
}

function toFields(
  columns: readonly Column[],
  kind: "column" | "parameter",
  dialect: Dialect,
  report: (problem: string) => void,
  describe: (column: Column, index: number) => Omit<Field, "key" | "column">,
): Field[] {
  const seen = new Set<string>();
  return columns.map((column, index) => {
    const key = camelCase(column.name);
    if (!IDENTIFIER.test(key)) {
      report(
        `${kind} "${column.name}" does not make a valid identifier; ${
          kind === "column"
            ? "alias it with AS"
            : `name it with ${dialect.namedParam}`
        }`,
      );
    } else if (seen.has(key)) {
      report(
        `two ${kind}s map to "${key}"; ${
          kind === "column"
            ? "alias one with AS"
            : `name them with ${dialect.namedParam}`
        }`,
      );
    }
    seen.add(key);
    return { key, column: column.name, ...describe(column, index) };
  });
}

type Resolve = (column: Column, role: "output" | "param") => string;

/** The embedded table's columns as fields, each read from the alias the SELECT gives it. */
function embedFields(
  embed: Embed,
  dialect: Dialect,
  resolve: Resolve,
  report: (problem: string) => void,
): Field[] {
  const fields = toFields(
    embed.columns.map(({ column }) => column),
    "column",
    dialect,
    (problem) => report(`${embed.name}: ${problem}`),
    (column) => ({ ts: resolve(column, "output"), nullable: !column.not_null }),
  );
  return fields.map((field, i) => ({
    ...field,
    column: embed.columns[i]?.alias ?? field.column,
  }));
}

/**
 * Declares (once per file) and names the type of an embedded table's row: the table name
 * in PascalCase, as sqlc's own generators name their models.
 */
function embedType(
  embed: Embed,
  enums: EnumTypes,
  used: Used,
  dialect: Dialect,
  resolve: Resolve,
  report: (problem: string) => void,
): string {
  const tsName = pascalCase(embed.table.rel.name);
  if (RUNTIME_TYPES.has(tsName) || [...enums.values()].includes(tsName)) {
    report(
      `sqlc.embed(${embed.table.rel.name}): its type would be named ${tsName}, which the generated file already uses`,
    );
    return "unknown";
  }
  if (!used.embeds.has(tsName)) {
    used.embeds.set(
      tsName,
      `export type ${tsName} = ${objectType(embedFields(embed, dialect, resolve, report))};\n`,
    );
  }
  return tsName;
}

/**
 * `-- @nullable col ...` and `-- @notnull col ...` above a query override sqlc's
 * nullability for result columns. It needs them where it guesses wrong: a cast always
 * reads as NOT NULL, and so does an aggregate such as max() over an outer join.
 */
function parseDirectives(
  comments: readonly string[],
  report: (problem: string) => void,
): Directives {
  const directives: Directives = {
    nullable: new Set(),
    notNull: new Set(),
    docs: [],
  };
  for (const raw of comments) {
    const line = raw.trim();
    const match = /^@(\w+)\s*(.*)$/.exec(line);
    if (!match) {
      directives.docs.push(line);
      continue;
    }
    const [, name, rest] = match;
    const target =
      name === "nullable"
        ? directives.nullable
        : name === "notnull"
          ? directives.notNull
          : null;
    if (!target) {
      report(`unknown directive @${name}`);
      continue;
    }
    for (const column of rest.split(/[\s,]+/).filter(Boolean)) {
      target.add(column);
    }
  }
  return directives;
}

function renderFile(
  filename: string,
  sqlcVersion: string,
  blocks: readonly string[],
  used: Used,
): string {
  const importLine = (
    names: ReadonlySet<string>,
    from: string,
    kind = "type ",
  ) =>
    names.size > 0
      ? `import ${kind}{ ${[...names].sort().join(", ")} } from "${from}";\n`
      : "";
  const imports =
    importLine(used.enums, "./enums") +
    importLine(used.runtime, "./runtime") +
    importLine(used.helpers, "./runtime", "");
  const embeds = [...used.embeds.values()];
  return `${header(filename, sqlcVersion)}\n${imports}\n${[...embeds, ...blocks].join("\n")}`;
}

export function header(source: string, sqlcVersion: string): string {
  return `${GENERATED_MARKER} from ${source} (sqlc ${sqlcVersion}). DO NOT EDIT.\n`;
}

function objectType(fields: readonly Field[]): string {
  const lines = fields.map(
    (field) => `  ${field.key}: ${field.ts}${field.nullable ? " | null" : ""};`,
  );
  return `{\n${lines.join("\n")}\n}`;
}

function rowMapper(fields: readonly Field[], indent = "    "): string {
  const lines = fields.map((field) => {
    if (field.embed) {
      const nested = rowMapper(field.embed, `${indent}  `);
      // A LEFT JOIN that matched nothing leaves every embedded column NULL.
      const value = field.nullable
        ? `[${field.embed.map((f) => access(f)).join(", ")}].every((v) => v === null) ? null : ${nested}`
        : nested;
      return `${indent}${field.key}: ${value},`;
    }
    const ts = field.nullable ? `${field.ts} | null` : field.ts;
    return `${indent}${field.key}: ${access(field)} as ${ts},`;
  });
  return `{\n${lines.join("\n")}\n${indent.slice(2)}}`;
}

function access(field: Field): string {
  return IDENTIFIER.test(field.column)
    ? `row.${field.column}`
    : `row[${JSON.stringify(field.column)}]`;
}

function jsdoc(lines: readonly string[]): string {
  const body = lines.map((line) => ` * ${line.replaceAll("*/", "*\\/")}`);
  return `/**\n${body.join("\n")}\n */\n`;
}

function escapeTemplate(text: string): string {
  return text
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");
}

export function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

export function pascalCase(name: string): string {
  return name
    .split("_")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}
